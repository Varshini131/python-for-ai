
# Python Variables
# String
name = "Varshini"

# Integer
age = 20

# Float
cgpa = 8.0

# Boolean
is_student = True

# Printing variables
print("Name:", name)
print("Age:", age)
print("CGPA:", cgpa)
print("Student:", is_student)

print()

# Multiple Variable Assignment
x, y, z = 10, 20, 30

print("x =", x)
print("y =", y)
print("z =", z)

print()

# Assign Same Value to Multiple Variables

a = b = c = 100

print("a =", a)
print("b =", b)
print("c =", c)

print()

# Dynamic Typing


value = 100
print(value)

value = "Python for AI"
print(value)

value = 99.5
print(value)

print()


# Checking Data Types


print(type(name))
print(type(age))
print(type(cgpa))
print(type(is_student))